/*
执行栈,宏任务队列,微任务队列,宿主环境(浏览器、nodejs),事件循环

1. setTimeout, setInterval, new Promise未触发先放在宿主环境等待触发，触发后setTimeout, setInerval的回调函数放入宏任务队列
2. `new Promise(executor)` 的**executor 函数是同步执行，直接进执行栈**，不是放宿主等待；
   `.then/.catch/.finally` 回调才是微任务。`.then`等执行栈执行到了resolve函数后放入微任务队列,
   `.catch`则是等reject函数执行到后把回调函数放入微任务队列, `.finally`则等`.then/.catch`执行完后把回调函数加入微任务队列
3. 执行栈一直执行到没有之后, 去微任务队列看是否有任务有就拿来执行, 直到微任务队列任务被消费完;
【如果是浏览器，3-4之间会看是否需要渲染，需要则渲染再执行步骤4】
4. 微任务队列消费完后就去宏任务队列找一个任务来消费, 没有休眠一段时间后再来宏任务队列找,
   有任务之后就消费,消费完就去消费完微任务队列的任务,循此往复

主线程就负责执行宏任务、微任务，至于托管在宿主环境的setTimeout这些时机到了宿主环境有线程负责把宏任务丢到队列中，不需要主线程管。
* */
